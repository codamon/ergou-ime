// Every pinyin translator (二狗拼音, and the pinyin half of 五笔拼音混输) uses
// the dictionary `ergou_pinyin_dict`. It has no entries of its own; it only
// imports other tables:
//
//   拼音大词库 installed:  cn_dicts/8105, cn_dicts/base, cn_dicts/ext
//                          (rime-ice 2026.06.30, about 89 万 entries)
//     + 腾讯词库 installed: cn_dicts/tencent (about 98 万 more; optional,
//                          only used together with 拼音大词库)
//   not installed:         pinyin_simp (bundled with rime-wubi86-jidian,
//                          about 10 万 entries; the fallback)
//
// RimeData/ergou_pinyin_dict.dict.yaml (bundled) is the fallback version;
// `sync(_:)` writes the real one into the Rime user directory before every
// deployment, and librime prefers the user directory's copy.
//
// ErgouIME Settings downloads the packages into the App Group container
// (Paths.models/pinyin-dict, Paths.models/pinyin-dict-tencent). Settings has
// network access, so the input method checks the files against SHA-256
// values fixed in the code (SpeechModelFiles), copies them into its own
// private Rime user directory and checks the copies again before librime
// parses them. A file Settings swaps later is never read: librime only sees
// the copies (Shared/Paths.swift explains why Settings never writes Rime
// files).

import Foundation

enum PinyinDictionary {
    static let package = SpeechModelFiles.pinyinDictRimeIce
    static let tencent = SpeechModelFiles.pinyinDictTencent
    static let dictName = "ergou_pinyin_dict"
    static let importedName = "ergou_imported"
    static let importedAutoName = "ergou_imported_auto"

    /// The two 个人词库 tables, from the validated shared list: with pinyin,
    /// and without (Rime spells those from the character readings).
    static func importedYAML() -> (withPinyin: String, auto: String) {
        let words = ImportedWords.load()
        let header = "# Generated by ErgouIME from 个人词库 (Shared/ImportedWords.swift). Edits are overwritten.\n---\n"
        let spelled = words.compactMap { w in w.pinyin.map { "\(w.text)\t\($0)\t\(ImportedWords.weight)" } }
        let auto = words.filter { $0.pinyin == nil }.map { "\($0.text)\t\(ImportedWords.weight)" }
        let a = header + "name: \(importedName)\nversion: \"\(spelled.count)\"\nsort: by_weight\n...\n"
            + spelled.joined(separator: "\n") + (spelled.isEmpty ? "" : "\n")
        let b = header + "name: \(importedAutoName)\nversion: \"\(auto.count)\"\nsort: by_weight\ncolumns:\n  - text\n  - weight\n...\n"
            + auto.joined(separator: "\n") + (auto.isEmpty ? "" : "\n")
        return (a, b)
    }
    /// Folder under the Rime user directory holding the copies. Matches the
    /// relative paths in the packages ("cn_dicts/base.dict.yaml").
    static let localFolder = "cn_dicts"

    /// Copies the verified packages into `user` (or removes old copies when
    /// a package is gone) and returns the dictionary file to write.
    static func sync(_ user: URL) -> (yaml: String, large: Bool, tencent: Bool) {
        let large = package.isIntact && copy(package, into: user)
        let withTencent = large && tencent.isIntact && copy(tencent, into: user)
        let fm = FileManager.default
        if !large {
            let folder = user.appendingPathComponent(localFolder, isDirectory: true)
            if fm.fileExists(atPath: folder.path) { try? fm.removeItem(at: folder) }
        } else if !withTencent {
            for name in tencent.files.keys {
                let copy = user.appendingPathComponent(name)
                if fm.fileExists(atPath: copy.path) { try? fm.removeItem(at: copy) }
            }
        }
        return (dictYAML(large: large, tencent: withTencent), large, withTencent)
    }

    static func dictYAML(large: Bool, tencent withTencent: Bool) -> String {
        var tables = ["pinyin_simp"]
        if large {
            // Character table first, then base, ext, tencent: with duplicates
            // the first table's weight wins (rime-ice's own order).
            tables = ["cn_dicts/8105", "cn_dicts/base", "cn_dicts/ext"]
            if withTencent { tables.append("cn_dicts/tencent") }
        }
        // 个人词库 last: words the main tables already have keep their weight
        // (Shared/ImportedWords.swift). Always present, possibly empty.
        tables += [importedName, importedAutoName]
        let version = large ? "rime-ice-2026.06.30" + (withTencent ? "+tencent" : "") : "pinyin_simp"
        return """
        # Generated by ErgouIME. Edits are overwritten (ErgouIME/Engine/PinyinDictionary.swift).
        ---
        name: \(dictName)
        version: "\(version)"
        sort: by_weight
        import_tables:
        \(tables.map { "  - \($0)" }.joined(separator: "\n"))
        ...

        """
    }

    /// Copies each file whose local copy is missing or different, then checks
    /// the copy (not the shared original) against the fixed SHA-256.
    private static func copy(_ files: SpeechModelFiles, into user: URL) -> Bool {
        let fm = FileManager.default
        for (name, sha) in files.files {
            let target = user.appendingPathComponent(name)
            if VerifiedFiles.shared.matches(target, sha256: sha) { continue }
            let temp = user.appendingPathComponent(".\(UUID().uuidString).tmp")
            defer { try? fm.removeItem(at: temp) }
            do {
                try fm.createDirectory(at: target.deletingLastPathComponent(), withIntermediateDirectories: true)
                try fm.copyItem(at: files.url(name), to: temp)
                guard FileHash.sha256(of: temp) == sha else {
                    Log.engine.error("Pinyin dictionary copy failed its check; not using it")
                    return false
                }
                if fm.fileExists(atPath: target.path) { try fm.removeItem(at: target) }
                try fm.moveItem(at: temp, to: target)
            } catch {
                Log.engine.error("Could not copy the pinyin dictionary; not using it")
                return false
            }
        }
        return true
    }
}
