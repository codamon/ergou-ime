// The Rime user directory lives in the input method's private container
// (Shared/Paths.swift). ErgouIME Settings never writes it; it stores values in
// the shared UserDefaults and posts SharedNotifications.redeployRime. Before
// every deployment the input method calls `RimeUserConfig.prepare(_:)`, which
//
//   1. quarantines rime.lua and lua/ if they appeared in the user directory
//      (librime-lua would load them before the bundled scripts);
//   2. regenerates, from SharedSettings (already validated):
//        default.custom.yaml           schema list = ergou_wubi
//        ergou_wubi.custom.yaml        调频, 自动上屏, 拼音降权, options for Lua
//        ergou_pinyin.custom.yaml      spelling algebra: fuzzy pairs, typo rules
//        ergou_pinyin_ime.custom.yaml  只用拼音: spelling, 双拼, 调频
//        wubi86_jidian_user.dict.yaml  manual phrases (手动造词)
//        ergou_phrases.txt             常用语 by code (lua/ergou/phrases.lua)
//        ergou_pinyin_dict.dict.yaml   which pinyin tables to import, plus
//                                      the checked copies of 拼音大词库 in
//                                      cn_dicts/ (PinyinDictionary.swift)
//
// Every value written here comes from an enum, a Bool, a constant, or a
// ManualPhrase that passed SettingsValidation — never a raw string from the
// shared defaults.

import Foundation

enum RimeUserConfig {
    /// Returns true if any generated file changed (a redeploy is needed).
    @discardableResult
    static func prepare(_ user: URL) -> Bool {
        quarantineScripts(in: user)
        var changed = false
        for (name, content) in files(user) {
            changed = write(content, to: user.appendingPathComponent(name)) || changed
        }
        return changed
    }

    // MARK: - Lua quarantine

    private static func quarantineScripts(in user: URL) {
        let fm = FileManager.default
        let suspects = ["rime.lua", "lua"].map { user.appendingPathComponent($0) }
            .filter { fm.fileExists(atPath: $0.path) }
        guard !suspects.isEmpty else { return }
        let stamp = ISO8601DateFormatter().string(from: Date())
            .replacingOccurrences(of: ":", with: "-")
        let box = user.deletingLastPathComponent()
            .appendingPathComponent("Quarantine", isDirectory: true)
            .appendingPathComponent(stamp, isDirectory: true)
        do {
            try fm.createDirectory(at: box, withIntermediateDirectories: true)
            for item in suspects {
                try fm.moveItem(at: item, to: box.appendingPathComponent(item.lastPathComponent))
            }
            Log.engine.error("Moved unexpected Lua files out of the Rime user directory")
        } catch {
            // Never load them: delete if they cannot be moved.
            for item in suspects { try? fm.removeItem(at: item) }
            Log.engine.error("Could not quarantine Lua files; deleted them")
        }
    }

    // MARK: - Generated files

    private static let header = "# Generated by ErgouIME from its settings. Edits are overwritten.\n"

    private static func files(_ user: URL) -> [(String, String)] {
        [
            ("default.custom.yaml", defaultCustom()),
            ("ergou_wubi.custom.yaml", wubiCustom()),
            ("ergou_pinyin.custom.yaml", pinyinCustom()),
            ("ergou_pinyin_ime.custom.yaml", pinyinIMECustom()),
            ("wubi86_jidian_user.dict.yaml", userDict()),
            ("ergou_phrases.txt", quickPhrases()),
            ("\(PinyinDictionary.dictName).dict.yaml", PinyinDictionary.sync(user).yaml),
        ]
    }

    private static func defaultCustom() -> String {
        header + """
        patch:
          schema_list:
            - schema: \(SharedSettings.inputScheme.schemaID)
          menu/page_size: 5

        """
    }

    /// See RimeData/ergou_wubi.schema.yaml for what each key does.
    private static func wubiCustom() -> String {
        let learn = SharedSettings.frequencyLearning
        let autoCommit = SharedSettings.autoCommitUnique
        let correction = SharedSettings.pinyinCorrection
        let fuzzy = SharedSettings.fuzzyPinyin.map(\.rawValue).joined(separator: ", ")
        return header + """
        patch:
          translator/enable_user_dict: \(learn)
          pinyin/enable_user_dict: \(learn)
          # Adjacent-key correction only after the ` prefix: in mixed input it
          # turns wubi codes into junk pinyin (tested on a Mac, 2026-11-09).
          pinyin/enable_correction: false
          pinyin_only/enable_correction: \(correction)
          ergou/auto_commit: \(autoCommit)
          ergou/auto_commit_strict: \(SharedSettings.autoCommitStrict)
          ergou/fuzzy: [\(fuzzy)]
          ergou/pinyin_correction: \(correction)
          ergou/wubi_correction: \(SharedSettings.wubiCorrection)

        """
    }

    /// Must stay in step with RimeData/ergou_pinyin.schema.yaml (defaults)
    /// and RimeData/lua/ergou/pinyin.lua (the Lua mirror).
    /// The two ü rules cover both dictionaries: pinyin_simp spells 略 "lue",
    /// rime-ice "lve"; either way both lue and lve can be typed.
    static let baseAlgebra = [
        "derive/^([nl])ue$/$1ve/",
        "derive/^([nl])ve$/$1ue/",
        "derive/^([jqxy])u/$1v/",
        "derive/un$/uen/",
        "derive/ui$/uei/",
        "derive/iu$/iou/",
    ]
    static let typoAlgebra = [
        "derive/([aeiou])ng$/$1gn/",
        "derive/ong$/on/",
        "derive/ao$/oa/",
        "derive/([iu])a(o|ng?)$/a$1$2/",
    ]

    private static func pinyinCustom() -> String {
        var rules = baseAlgebra
        for pair in SharedSettings.fuzzyPinyin { rules += pair.algebra }
        if SharedSettings.pinyinCorrection { rules += typoAlgebra }
        let list = rules.map { "      - \"\($0)\"" }.joined(separator: "\n")
        return header + """
        patch:
          speller/algebra:
        \(list)

        """
    }

    /// Pinyin-only mode (ergou_pinyin_ime): same spelling rules, plus
    /// initials (zg → 中国); adjacent-key correction is safe here because
    /// there are no wubi codes to collide with.
    private static func pinyinIMECustom() -> String {
        let shuangpin = SharedSettings.shuangpin
        var rules: [String] = []
        if shuangpin == .none {
            rules = baseAlgebra
            for pair in SharedSettings.fuzzyPinyin { rules += pair.algebra }
            if SharedSettings.pinyinCorrection { rules += typoAlgebra }
            rules += ["abbrev/^([a-z]).+$/$1/", "abbrev/^([zcs]h).+$/$1/"]
        } else {
            // 双拼: fuzzy rules on full pinyin first, then the two-key conversion.
            for pair in SharedSettings.fuzzyPinyin { rules += pair.algebra }
            rules += shuangpin.algebra
        }
        let list = rules.map { "      - \"\($0)\"" }.joined(separator: "\n")
        let alphabet = "zyxwvutsrqponmlkjihgfedcba" + (shuangpin.usesSemicolon ? ";" : "")
        // 双拼: show the codes as full pinyin (the schema's rules are for
        // full pinyin and garble two-key codes). Single-quoted: the rules
        // contain backslashes.
        var preedit = ""
        if shuangpin != .none {
            preedit = "  translator/preedit_format:\n"
                + shuangpin.preeditFormat.map { "    - \(yamlSingleQuoted($0))\n" }.joined()
        }
        return header + """
        patch:
          translator/enable_user_dict: \(SharedSettings.frequencyLearning)
          translator/enable_correction: \(SharedSettings.pinyinCorrection)
          ergou/shuangpin: \(shuangpin != .none)
          speller/alphabet: "\(alphabet)"
          speller/initials: "zyxwvutsrqponmlkjihgfedcba"
          speller/algebra:
        \(list)

        """ + preedit
    }

    /// A YAML single-quoted scalar: no escapes inside, quotes are doubled.
    private static func yamlSingleQuoted(_ s: String) -> String {
        "'" + s.replacingOccurrences(of: "'", with: "''") + "'"
    }

    /// 常用语 with a code, read by lua/ergou/phrases.lua. Only validated
    /// entries (SettingsValidation.quickPhrase); written as QuickPhrase.stored.
    /// The first line is a checksum of the rest: phrases.lua re-reads only
    /// that line while typing and loads the whole file when it changes.
    private static func quickPhrases() -> String {
        let body = SharedSettings.quickPhrases.filter { !$0.code.isEmpty }.map(\.stored).joined(separator: "\n") + "\n"
        var hash: UInt64 = 0xcbf2_9ce4_8422_2325          // FNV-1a, stable across launches
        for byte in body.utf8 { hash = (hash ^ UInt64(byte)) &* 0x0000_0100_0000_01b3 }
        return "# " + String(hash, radix: 16) + "\n" + body
    }

    /// Settings saved 常用语: only ergou_phrases.txt changes, and
    /// phrases.lua picks it up within a second — no redeploy, so typing is
    /// not interrupted.
    static func writePhrases(_ user: URL) {
        write(quickPhrases(), to: user.appendingPathComponent("ergou_phrases.txt"))
    }

    /// Imported by wubi86_jidian.dict.yaml (import_tables: wubi86_jidian_user).
    /// librime should prefer this copy over the bundled one — verify (M3 T3.8).
    private static func userDict() -> String {
        let rows = SharedSettings.manualPhrases.map { "\($0.text)\t\($0.code)" }
        return header + """
        ---
        name: wubi86_jidian_user
        version: "1"
        sort: original
        ...

        """ + rows.joined(separator: "\n") + (rows.isEmpty ? "" : "\n")
    }

    // MARK: - IO

    @discardableResult
    private static func write(_ content: String, to url: URL) -> Bool {
        if let old = try? String(contentsOf: url, encoding: .utf8), old == content { return false }
        do {
            try content.write(to: url, atomically: true, encoding: .utf8)
            return true
        } catch {
            Log.engine.error("Could not write a Rime user file")
            return false
        }
    }
}
