#   python3 scripts/gen-english-dict.py SRC_DIR COMMIT
#
# SRC_DIR holds en.dict.yaml and en_ext.dict.yaml from rime-ice's en_dicts/
# at COMMIT (https://github.com/iDvel/rime-ice, GPL-3.0). Download them from
# https://raw.githubusercontent.com/iDvel/rime-ice/<COMMIT>/en_dicts/<file>.
#
# Rules (D, 2026-11-11): commit the standard spelling (python → Python), one
# word per code, letters only.
#   * the code is the word in lower case;
#   * tools/english-dict/casing.txt replaces every spelling of its codes;
#   * otherwise the first spelling in en.dict.yaml (rime-ice's main list of
#     real words: may, not the app "May"); en_ext.dict.yaml (abbreviations,
#     product names) only adds codes the main list lacks;
#   * single letters are left out (rime-ice comments them out too).
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
WORD = re.compile(r"^[A-Za-z]{2,}$")


def entries(path):
    started = False
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("..."):
            started = True
            continue
        if not started or not line.strip() or line.startswith("#"):
            continue
        text = line.split("\t")[0]
        if WORD.match(text):
            yield text


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__ or "usage: gen-english-dict.py SRC_DIR COMMIT")
    src, commit = pathlib.Path(sys.argv[1]), sys.argv[2]
    chosen = {}  # code -> text; the main list first, then en_ext
    for name in ("en.dict.yaml", "en_ext.dict.yaml"):
        for text in entries(src / name):
            chosen.setdefault(text.lower(), text)

    fixed = {}
    for line in (ROOT / "tools/english-dict/casing.txt").read_text(encoding="utf-8").splitlines():
        word = line.strip()
        if not word or word.startswith("#"):
            continue
        if not WORD.match(word):
            sys.exit(f"casing.txt: not letters only: {word!r}")
        if word.lower() in fixed:
            sys.exit(f"casing.txt: duplicate: {word!r}")
        fixed[word.lower()] = word

    chosen.update(fixed)

    out = ROOT / "RimeData/ergou_en.dict.yaml"
    with out.open("w", encoding="utf-8") as f:
        f.write(
            "# ergou-ime — 中英混输的英文词库（GENERATED by scripts/gen-english-dict.py; do not edit）\n"
            "# SPDX-License-Identifier: GPL-3.0-only\n"
            "#\n"
            f"# From rime-ice en_dicts (en + en_ext) at commit {commit}\n"
            "# (https://github.com/iDvel/rime-ice, GPL-3.0), spellings fixed by\n"
            "# tools/english-dict/casing.txt. Code = the word in lower case.\n"
            "---\n"
            "name: ergou_en\n"
            f'version: "rime-ice-{commit[:7]}"\n'
            "sort: original\n"
            "columns:\n"
            "  - text\n"
            "  - code\n"
            "...\n"
        )
        for code in sorted(chosen):
            f.write(f"{chosen[code]}\t{code}\n")
    print(f"{out.relative_to(ROOT)}: {len(chosen)} words ({len(fixed)} from casing.txt)")


if __name__ == "__main__":
    main()
