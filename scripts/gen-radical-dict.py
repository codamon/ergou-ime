#!/usr/bin/env python3
# ergou-ime — build the 拆字 dictionary and schema from rime-ice's copy of
# rime-radical-pinyin.
# SPDX-License-Identifier: GPL-3.0-only
#
#   python3 scripts/gen-radical-dict.py SRC_DIR COMMIT
#
# SRC_DIR holds radical_pinyin.dict.yaml and radical_pinyin.schema.yaml from
# https://raw.githubusercontent.com/iDvel/rime-ice/<COMMIT>/ (rime-ice ships
# the release of https://github.com/mirtlecn/rime-radical-pinyin, © Mirtle,
# GPL-3.0; table from 开放词典 / henrysting / Mirtle).
#
# Writes
#   RimeData/ergou_radical.dict.yaml    the table, comments removed
#   RimeData/ergou_radical.schema.yaml  only there so that deployment builds
#       the prism; carries upstream's spelling rules for full pinyin and the
#       three 双拼 we offer (the input method picks one, RimeUserConfig.swift)
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
RULES = {  # ours → upstream
    "algebra_none": "algebra_rime_ice",
    "algebra_xiaohe": "algebra_double_pinyin_flypy",
    "algebra_ziranma": "algebra_double_pinyin",
    "algebra_microsoft": "algebra_double_pinyin_mspy",
}


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: gen-radical-dict.py SRC_DIR COMMIT")
    src, commit = pathlib.Path(sys.argv[1]), sys.argv[2]

    lines = (src / "radical_pinyin.dict.yaml").read_text(encoding="utf-8").splitlines()
    end = lines.index("...")
    version = next(l.split('"')[1] for l in lines[:end] if l.startswith("version:"))
    rows = [l for l in lines[end + 1:] if l and not l.startswith("#")]
    for row in rows:
        if not re.fullmatch(r"[^\t]+\t[a-z']+(\t\d+)?", row):
            sys.exit(f"unexpected row: {row!r}")
    (ROOT / "RimeData/ergou_radical.dict.yaml").write_text(
        "# ergou-ime — 拆字：用部件的拼音打字（` 开头）\n"
        "# Generated by scripts/gen-radical-dict.py; do not edit.\n"
        f"# Source: rime-radical-pinyin {version} (https://github.com/mirtlecn/rime-radical-pinyin,\n"
        f"# © Mirtle, GPL-3.0; 码表：开放词典 / henrysting / Mirtle), as shipped in rime-ice {commit}.\n"
        "---\nname: ergou_radical\n"
        f'version: "{version}"\nsort: original\n...\n\n' + "\n".join(rows) + "\n", encoding="utf-8")

    schema = (src / "radical_pinyin.schema.yaml").read_text(encoding="utf-8")
    blocks = []
    for ours, theirs in RULES.items():
        m = re.search(rf"^{theirs}:\n((?:  - .*\n)+)", schema, re.M)
        if not m:
            sys.exit(f"{theirs} not found in radical_pinyin.schema.yaml")
        blocks.append(f"{ours}:\n{m.group(1)}")
    (ROOT / "RimeData/ergou_radical.schema.yaml").write_text(
        "# ergou-ime — 拆字的拼写（只作依赖，不出现在方案列表里）\n"
        "# SPDX-License-Identifier: GPL-3.0-only\n"
        "# Generated by scripts/gen-radical-dict.py; do not edit.\n"
        "#\n"
        "# Exists so that deployment compiles the \"ergou_radical\" prism for\n"
        "# table_translator@radical in ergou_pinyin_ime (` + the pinyin of a\n"
        "# character's parts: `niuniuniu → 犇). The spelling rules below are\n"
        "# rime-radical-pinyin's (© Mirtle, GPL-3.0), which keep the parts apart\n"
        "# (\"niu'niu'niu\") while turning each into its 双拼 code. The input method\n"
        "# writes ergou_radical.custom.yaml to pick the set that matches 拼音方案.\n\n"
        "schema:\n  schema_id: ergou_radical\n  name: 二狗·拆字拼写\n"
        f'  version: "{version}"\n  description: |\n    拆字的部件拼写。不单独使用。\n\n'
        "engine:\n  processors: []\n  segmentors: []\n  translators:\n    - table_translator\n\n"
        "speller:\n  alphabet: \"zyxwvutsrqponmlkjihgfedcba;\"\n  delimiter: \" '\"\n"
        "  algebra:\n    __include: algebra_none\n\n"
        "translator:\n  dictionary: ergou_radical\n  enable_user_dict: false\n\n"
        + "\n".join(blocks), encoding="utf-8")
    print(f"ergou_radical: {len(rows)} rows, rime-radical-pinyin {version}")


if __name__ == "__main__":
    main()
