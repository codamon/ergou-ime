#
#   python3 scripts/gen-shuangpin-codes.py
#
# Applies each 双拼 scheme's spelling algebra (Shared/InputOptions.swift,
# Shuangpin.algebra) to every pinyin syllable (RimeData/lua/ergou/pinyin.lua,
# BASE) the way librime does, and writes the set of two-key codes per scheme.
# lua/ergou/english.lua uses it to tell whether an English word is also
# typeable 双拼 (then the word goes second). Re-run after changing either.
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent


def syllables():
    lua = (ROOT / "RimeData/lua/ergou/pinyin.lua").read_text(encoding="utf-8")
    base = re.search(r"local BASE = \[\[(.*?)\]\]", lua, re.S).group(1).split()
    # pinyin_simp spells ü "lue/nue", rime-ice "lve/nve" (pinyin.lua BASE_RULES).
    return set(base) | {"lve", "nve"}


def algebras():
    swift = (ROOT / "Shared/InputOptions.swift").read_text(encoding="utf-8")
    body = swift[swift.index("var algebra: [String]"):swift.index("var preeditFormat")]
    out = {}
    for name, block in re.findall(r"case \.(\w+): return \[(.*?)\]\n", body, re.S):
        out[name] = re.findall(r'"((?:[^"\\]|\\.)*)"', block)
    return out


def apply(rule, spellings):
    op, rest = rule.split("/", 1)
    if op == "xlit":
        left, right, _ = rest.split("/")
        table = str.maketrans(left, right)
        return {s.translate(table) for s in spellings}
    pattern, *repl = rest.rstrip("/").split("/")
    rx = re.compile(pattern)
    if op == "erase":
        return {s for s in spellings if not rx.search(s)}
    sub = re.sub(r"\$(\d)", r"\\\1", repl[0])
    changed = {s: rx.sub(sub, s) for s in spellings}
    if op == "xform":
        return set(changed.values())
    if op == "derive":
        return set(spellings) | set(changed.values())
    raise SystemExit(f"unknown rule {rule!r}")


def main():
    lines = [
        "-- ergou-ime — two-key codes of each 双拼 scheme (中英混输).",
        "-- SPDX-License-Identifier: GPL-3.0-only",
        "-- GENERATED by scripts/gen-shuangpin-codes.py from Shared/InputOptions.swift",
        "-- and RimeData/lua/ergou/pinyin.lua; do not edit.",
        "",
        "return {",
    ]
    for name, rules in algebras().items():
        if not rules:
            continue                          # .none = 全拼
        s = syllables()
        for rule in rules:
            s = apply(rule, s)
        codes = sorted(c for c in s if len(c) == 2)
        # derive rules keep the original too (微软 o → oo, o stays): a
        # one-key leftover is not a 双拼 code, so it is not listed.
        lines.append(f"  {name} = {{")
        for i in range(0, len(codes), 16):
            lines.append("    " + " ".join(f'["{c}"]=true,' for c in codes[i:i + 16]))
        lines.append("  },")
        print(f"{name}: {len(codes)} codes")
    lines.append("}")
    (ROOT / "RimeData/lua/ergou/shuangpin_codes.lua").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
