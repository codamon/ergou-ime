#!/usr/bin/env bash
# ergou-ime — write Config/Local.xcconfig from what is present in vendor/.
# SPDX-License-Identifier: GPL-3.0-only
#
# Run after any fetch-*.sh, then `xcodegen generate` (bootstrap.sh does both).
#
# Requires ERGOU_TEAM_ID (your 10-character Apple Developer Team ID) in the
# environment. It is written only to Config/Local.xcconfig, which is
# git-ignored; it must never be committed. Find it in Xcode → Settings →
# Accounts, or at https://developer.apple.com/account (Membership details).
source "$(dirname "$0")/lib/common.sh"

out="$REPO_ROOT/Config/Local.xcconfig"
conditions=() headers=() libdirs=() ldflags=()

team="${ERGOU_TEAM_ID:-}"
if [[ -z "$team" && -f "$out" ]]; then
  # Keep the value from an earlier run.
  team="$(sed -n 's/^ERGOU_TEAM_ID = //p' "$out")"
fi
[[ "$team" =~ ^[A-Z0-9]{10}$ ]] || die "set ERGOU_TEAM_ID to your 10-character Apple Developer Team ID (e.g. export ERGOU_TEAM_ID=AB12CD34EF)"
log "Team ID: set (App Group ${team}.com.codamon.ergou)"

if [[ -f "$VENDOR_DIR/librime/include/rime_api.h" && -f "$VENDOR_DIR/librime/lib/librime.dylib" ]]; then
  conditions+=(ERGOU_WITH_RIME)
  headers+=('$(SRCROOT)/vendor/librime/include')
  libdirs+=('$(SRCROOT)/vendor/librime/lib')
  ldflags+=(-lrime)
  if [[ ! -d "$VENDOR_DIR/rime-data" ]]; then
    warn "librime found but vendor/rime-data is missing — run scripts/fetch-rime-data.sh"
  fi
  log "librime: enabled"
else
  log "librime: not found (passthrough engine only)"
fi

if [[ -f "$VENDOR_DIR/sherpa-onnx/include/sherpa-onnx/c-api/c-api.h" ]]; then
  conditions+=(ERGOU_WITH_SHERPA)
  headers+=('$(SRCROOT)/vendor/sherpa-onnx/include')
  libdirs+=('$(SRCROOT)/vendor/sherpa-onnx/lib')
  ldflags+=(-lsherpa-onnx-c-api -lonnxruntime)
  log "sherpa-onnx: enabled"
else
  log "sherpa-onnx: not found (speech disabled)"
fi

llama_conditions="" llama_headers="" llama_libdirs="" llama_ldflags=""
if [[ -f "$VENDOR_DIR/llama/include/llama.h" && -f "$VENDOR_DIR/llama/lib/libllama.0.dylib" ]]; then
  llama_conditions="ERGOU_WITH_LLAMA"
  llama_headers='$(SRCROOT)/vendor/llama/include'
  llama_libdirs='$(SRCROOT)/vendor/llama/lib'
  llama_ldflags="-lllama"
  log "llama.cpp: enabled (voice correction, local models)"
else
  log "llama.cpp: not found (local voice correction disabled)"
fi
{
  echo "// Generated by scripts/configure.sh — do not edit, do not commit."
  echo "ERGOU_TEAM_ID = $team"
  echo "ERGOU_EXTRA_SWIFT_CONDITIONS = ${conditions[*]:-}"
  echo "ERGOU_EXTRA_HEADER_SEARCH_PATHS = ${headers[*]:-}"
  echo "ERGOU_EXTRA_LIBRARY_SEARCH_PATHS = ${libdirs[*]:-}"
  echo "ERGOU_EXTRA_LDFLAGS = ${ldflags[*]:-}"
  echo "ERGOU_LLAMA_SWIFT_CONDITIONS = $llama_conditions"
  echo "ERGOU_LLAMA_HEADER_SEARCH_PATHS = $llama_headers"
  echo "ERGOU_LLAMA_LIBRARY_SEARCH_PATHS = $llama_libdirs"
  echo "ERGOU_LLAMA_LDFLAGS = $llama_ldflags"
} > "$out"
log "wrote ${out#$REPO_ROOT/}"
